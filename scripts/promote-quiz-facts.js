// Promote REVIEWED structured quiz facts into the app.
//
// Reads content-sources/quiz-facts/<iso>.json and writes src/data/quizFacts.js
// — a bundled, synchronous accessor in the countryMetrics.js mould, so a round
// builds without a network call. A field is promoted only if it is BOTH
// `usable` (one value, sources agree) AND `review: "approved"` by a human
// (quizFactPolicy.isPromotable). Everything else is reported and left out.
//
// This is a kids-adjacent product: there is deliberately no flag to skip the
// review gate.
//
// Run:  npx tsx scripts/promote-quiz-facts.js
// Then: npm run seed:content   (bumps content_version so clients refetch)
import { readFile, writeFile, readdir } from "node:fs/promises";
import path from "node:path";
import { isPromotable, QUIZ_FACT_FIELDS } from "../src/game/quizFactPolicy";

const DIR = "content-sources/quiz-facts";
const OUT = "src/data/quizFacts.js";

async function run() {
  const files = (await readdir(DIR)).filter((f) => /^[a-z]{2}\.json$/.test(f)).sort();
  const facts = {};
  const held = { pending: 0, rejected: 0, notUsable: 0 };
  for (const f of files) {
    const doc = JSON.parse(await readFile(path.join(DIR, f), "utf8"));
    for (const field of QUIZ_FACT_FIELDS) {
      const v = doc.fields?.[field];
      if (!v) continue;
      if (isPromotable(v)) {
        (facts[doc.iso] ??= {})[field] = v.value;
      } else if (v.status !== "usable") held.notUsable += 1;
      else if (v.review === "rejected") held.rejected += 1;
      else held.pending += 1;
    }
  }
  const promoted = Object.values(facts).reduce((n, f) => n + Object.keys(f).length, 0);
  const body = `// GENERATED by scripts/promote-quiz-facts.js — do not hand-edit.
//
// Structured quiz facts that passed BOTH gates: one unambiguous value the
// sources agree on (src/game/quizFactPolicy.js), and human approval in
// content-sources/quiz-facts/<iso>.json. Provenance (Wikidata CC0, CIA World
// Factbook public domain) and the evidence for every value live there.
//
// Synchronous by design, like countryMetrics.js: a quiz round is built from
// these without a network call.
export const QUIZ_FACTS = ${JSON.stringify(facts, null, 2)};

// One fact, or null when the country has none that passed review — callers
// treat null as "this country can't be asked about", never as a guess.
export function quizFactFor(code, field) {
  return QUIZ_FACTS[code]?.[field] ?? null;
}

// The countries a quiz on \`field\` may ask about.
export function countriesWithFact(field) {
  return Object.keys(QUIZ_FACTS).filter((code) => QUIZ_FACTS[code][field] != null);
}
`;
  await writeFile(OUT, body);
  console.log(
    `Promoted ${promoted} field value(s) for ${Object.keys(facts).length} countr${Object.keys(facts).length === 1 ? "y" : "ies"} → ${OUT}`
  );
  console.log(
    `Held back: ${held.pending} awaiting review, ${held.rejected} rejected, ${held.notUsable} not usable (missing/multiple/contested)`
  );
  if (promoted)
    console.log("Next: npm run seed:content — bumps content_version so clients refetch.");
}

run().catch((e) => {
  console.error(e);
  process.exit(1);
});
