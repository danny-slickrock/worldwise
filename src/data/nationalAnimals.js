// Hand-compiled rather than drafted from the Factbook/Wikidata pipeline (see
// docs/adr/0001), the same way currencies.js and languages.js were. A
// currency has one legal answer; a national animal is the LEAST codified of
// the three. Fewer than half of these states have ever legislated an
// official national animal. Where one is legally declared (Canada's beaver,
// Bangladesh/India's Bengal tiger, Nepal's cow, Pakistan's markhor, and
// several dozen more), this uses that designation. Where none exists, this
// picks whichever animal is most commonly cited for that country — a
// coat-of-arms supporter (Namibia's oryx, the many European heraldic lions),
// a flag motif (Kiribati's frigatebird), a conservation icon (Rwanda's
// mountain gorilla), or a naming origin (Singapore's lion). That is a
// judgment call for most entries here, not a fact with one right answer —
// worth a second pair of eyes before a classroom relies on it, the same
// spirit as currencies.js's and languages.js's own notes. A shared animal
// across several countries (the many lions, brown bears, and the three Gulf
// states' Arabian oryx) is expected, not a bug — the dedupe-by-name
// distractor logic in game/questions.js exists for exactly that case, the
// same way it does for currency/language.
//
// Like currencies.js/languages.js, the prompt and options are the animal's
